#!/bin/bash
# Opt-in compatibility profile measured by CLAPPER_CHECKPOINT.md.
set -euo pipefail
if [[ $# -lt 3 ]]; then
    echo "Usage: $0 RUNTIME APK ANDROID_ROOT [runtime arguments...]" >&2
    exit 2
fi
runtime="$1"
apk="$2"
android_root="$3"
shift 3
export MACAPK_ELFEXEC_PRESERVE_FILES=1 MACAPK_WINDOW_PRESERVE_DECOR=1
export MACAPK_SYSCALL_TEXT_SHADOW=1 MACAPK_SVC_SHADOW_ALL=1
export MACAPK_TPIDR_SHADOW=1 MACAPK_TPIDR_SHADOW_CALL=1 MACAPK_SHADOW_ORIGINAL_LR=1
export MACAPK_LINKED_SHADOWS=1 MACAPK_SHADOW_HOST_RETURN=1
export MACAPK_NO_GUEST_TEXT_PATCH=1 MACAPK_SVC_BRK_EXEC_ONLY=1
export MACAPK_JIT_FAULT_WX=1 MACAPK_DYNAMIC_SVC_BRK=1 MACAPK_DYNAMIC_SVC_SHADOW=1
export MACAPK_SVC_INLINE_DATA=1 MACAPK_PAIRIP_TLS_CANARY=1
export MACAPK_NATIVE_TEXTURE_WINDOW=1 MACAPK_QUIET_CLASSLOAD=1
export MACAPK_X18_REWRITE_GENERIC=0 MACAPK_RAW_SYSCALL_REDIRECT=0 MACAPK_NULL_RECOVERY_NEARNULL=0
exec "$runtime" --apk "$apk" --android-root "$android_root" "$@"
